           "| Mission priorities | Removal cost = weight × capability lost; removing a safety-critical guest is never proposed | B.0 | `governor/model.py` · add_mode_constraints() |",
           "", "## Findings while checking the PDF arithmetic", "",
           "* Annex B 'jury use' says *any four guests exceed the 10 t mass margin*. Two four-sets fit: "
           "G1+G2+G4+G5 = 7.61 t and G1+G3+G4+G5 = 9.61 t (test `test_annex_claim_any_four_exceed_mass_is_false_for_two_sets`).",
           "* Annex B suggests installed G2, G3, G4 as a Scenario A starting set; it weighs 10.04 t > 10 t, "
           "so the governor refuses it as a default (binding: mass).",
           "* Scenario B puts G2, G3, G4 and G5 aboard together (13.07 t, and G3 needs all of Bay 1 while G2 and G5 "
           "both need Bay 2 or half of Bay 1). Under A.3/A.4 that set cannot be admitted; B is run as a runtime "
