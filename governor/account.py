if __name__ == "__main__":
    out = loader.ROOT / "docs/PHYSICAL_ACCOUNT.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(), encoding="utf-8")
    print(f"wrote {out} ({len(rows())} tagged assumptions)")
