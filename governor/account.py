           "| Heat rejection | Judged at the envelope's warmest water (30 °C → 120 kW); loop failure (−40 %) is a stress test, not a verdict input | A.10 default envelope lists genset loss only | `governor/loader.py` · load_ship_budget() |",
           "| Electrical power | Degraded state may throttle/shed (D4) but never below a safety-critical floor, never stops a running non-interruptible charge, never raises a guest above its normal mode | A.9, B.0 | `governor/model.py` · add_mission_envelope_constraints() |",
