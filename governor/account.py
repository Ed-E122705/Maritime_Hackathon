"""Render docs/PHYSICAL_ACCOUNT.md from the tags in the config files (Annex C, D6).

Every config line tagged [ASSUMED] or [docx] becomes a row with its file:line, so each number the
software relied on that is not in Annex A/B can be traced to where it is read.
"""
from __future__ import annotations

import re

from . import loader

CLASS_OF = [("horizon", "Mission priorities"), ("landing", "State / installation"), ("uuv_ramp", "State / installation"),
            ("recovery_speed", "State / installation"), ("relaunch", "Guest behaviour"), ("allow_asset_loss", "Mission priorities"),
            ("first_action", "Compute · Response time"), ("step_interval", "Compute · Response time"),
            ("restore_hysteresis", "Electrical power"), ("lines_b", "Electrical power"), ("G2: stbd", "Electrical power"),
            ("weights", "Mission priorities"), ("compute", "Compute · Response time"), ("winch", "Guest behaviour"),
            ("charge", "Guest behaviour"), ("standby", "Guest behaviour"), ("full:", "Guest behaviour"),
            ("needs_bay_clear", "Positions"), ("data:", "Data links"), ("satcom", "Data links"), ("backbone", "Data links"),
            ("lost_line", "Electrical power"), ("wiring", "Electrical power"), ("slow", "Electrical power"),
            ("fast", "Electrical power"), ("power", "Electrical power"), ("roof", "Positions"), ("drone_clearance", "Positions"),
            ("bay", "Positions"), ("mast", "Positions"), ("hangar", "Positions"), ("cooling", "Heat rejection"),
            ("mass", "Mass / stability"), ("port_window", "State / installation"), ("removal", "State / installation"),
            ("silence", "Mission envelope")]

USED_IN = {"ship.yaml": "governor/loader.py · load_ship_budget()", "guest_overlays.yaml": "governor/loader.py · load_guest_data()",
           "ops.yaml": "governor/rightofway.py · simulate() / right_of_way() / shed()",
           "priorities": "governor/model.py · add_objectives()"}


def _class(text):
    t = text.lower()
    for k, c in CLASS_OF:
        if k in t:
            return c
    return "Anything else"


def rows():
    out = []
    files = [loader.ROOT / "config/ship.yaml", loader.ROOT / "config/guest_overlays.yaml", loader.ROOT / "config/ops.yaml"] + \
        sorted((loader.ROOT / "config/priorities").glob("*.yaml"))
    for f in files:
        lines = f.read_text().splitlines()
        for i, line in enumerate(lines, 1):
            m = re.search(r"#\s*\[(ASSUMED|docx)\]\s*(.*)", line)
            if not m:
                continue
            code = line.split("#")[0].strip()
            if line.lstrip().startswith("#   [") or (not code and i < 10):
                continue                                   # legend in the file header
            # continuation comments explain the line above
            j = i - 1
            while not code and j > 0:
                code = lines[j - 1].split("#")[0].strip()
                j -= 1
            why = m.group(2).strip()
            k = i
            while k < len(lines) and lines[k].strip().startswith("#") and "[" not in lines[k][:12]:
                why += " " + lines[k].strip().lstrip("#").strip()
                k += 1
            rel = f.relative_to(loader.ROOT)
            used = next((v for key, v in USED_IN.items() if key in str(rel)), "")
            out.append({"class": _class(code + " " + str(rel)), "tag": m.group(1), "value": code,
                        "why": why, "where": f"{rel}:{i}", "used": used})
    return out


